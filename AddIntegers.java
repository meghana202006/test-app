public class AddIntegers {

    public static void main(String[] args) {
        // Initializing two integers
        int num1 = 5;
        int num2 = 10;

        // Adding the integers
        int sum = num1 + num2;

        // Printing the result
        System.out.println("The sum of " + num1 + " and " + num2 + " is: " + sum);
    }
}
